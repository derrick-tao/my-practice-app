// Audio for every item: content-addressed files, generated only when missing, optionally pruned.
import { createHash } from 'node:crypto';
import { mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { itemPinyin } from './pinyin.ts';
import { ttsConfig as defaultTtsConfig } from '../tts.config.ts';
import type { Rendition } from '../src/content/types.ts';
import { buildSsml, spokenPrompt } from './tts/prompt.ts';
import type { TtsConfig } from './tts/config.ts';
import { createProvider, type ProviderDeps } from './tts/provider-factory.ts';
import type { TtsProvider, TtsRequest } from './tts/types.ts';
import type { SourceList } from './validate.ts';

export interface AudioOptions {
  /** Content-addressed store of real audio (the committed `audio/` folder). */
  audioStoreDir: string;
  /** Which provider generates audio, with the voice, rates and format (default: tts.config.ts). */
  tts?: TtsConfig;
  /**
   * Credentials, network and clock for the provider that `tts` selects. The default is the real
   * environment; tests stub the network here so the whole build runs against a fake service.
   */
  providerDeps?: ProviderDeps;
  /** A ready-made provider used instead of the one `tts` selects (store tests, silent audio). */
  provider?: TtsProvider;
  /**
   * Explicit opt-in (tests, pull-request CI, local work): audio missing from the store is replaced by
   * silent placeholder audio from this provider, kept in its own store that is never committed.
   * Without it, missing audio needs working provider credentials or the build fails.
   */
  placeholder?: { provider: TtsProvider; storeDir: string };
  /** Delete store files that no item references any more. */
  prune?: boolean;
  log?: (line: string) => void;
}

/** Where a finished audio file lives: `ref` is relative to the content root, `file` is on disk. */
export interface LocatedAudio {
  ref: string;
  file: string;
}

export interface ResolvedAudio {
  /** Parallel to the `sources` passed in: one entry per list, one per item. */
  lists: Array<Array<Record<Rendition, LocatedAudio>>>;
  stats: AudioStats;
}

export interface AudioStats {
  /** Distinct audio files this content needs. */
  needed: number;
  /** Files generated through the real provider in this run. */
  requested: number;
  /** Files replaced by silent placeholder audio (only with the explicit opt-in). */
  placeholders: number;
  /** Store files removed because nothing references them. */
  pruned: string[];
}

export class MissingAudioError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'MissingAudioError';
  }
}

interface Planned {
  name: string;
  request: TtsRequest;
}

const AUDIO_FILE = /^[0-9a-f]{32}\.[a-z0-9]+$/;

export async function resolveAudio(sources: SourceList[], options: AudioOptions): Promise<ResolvedAudio> {
  const { placeholder } = options;
  const log = options.log ?? (() => {});
  const tts = options.tts ?? defaultTtsConfig;
  const provider = options.provider ?? createProvider(tts, { log, ...options.providerDeps });

  // Plan every rendition of every item. `wanted` is keyed by file name so a prompt shared by several
  // items (or a repeated rendition) is only ever requested once.
  const wanted = new Map<string, TtsRequest>();
  const plans = sources.map((source) =>
    source.items.map((item) => {
      const planFor = (rendition: Rendition): { primary: Planned; fallback?: Planned } => {
        const label = `${source.id}/${item.target} ${rendition}`;
        const primary = plan(provider, tts, item, rendition, label);
        wanted.set(primary.name, primary.request);
        return { primary, ...(placeholder && { fallback: plan(placeholder.provider, tts, item, rendition, label) }) };
      };
      return { normal: planFor('normal'), slow: planFor('slow') };
    }),
  );

  const missing: string[] = [];
  for (const name of wanted.keys()) {
    if (!(await exists(path.join(options.audioStoreDir, name)))) missing.push(name);
  }

  const stats: AudioStats = { needed: wanted.size, requested: 0, placeholders: 0, pruned: [] };
  const usePlaceholder = missing.length > 0 && placeholder !== undefined;

  if (missing.length > 0 && !usePlaceholder) {
    const problem = provider.unavailableReason?.();
    if (problem) {
      throw new MissingAudioError(
        `${missing.length} audio file(s) are missing and cannot be generated: ${problem}. ` +
          `Real audio is generated by the main deploy workflow (npm run audio:generate) and committed to ` +
          `${path.basename(options.audioStoreDir)}/; to generate it locally, put the key in .env (see ` +
          `.env.example) and run npm run audio:generate. For local work or a pull request, rebuild with ` +
          `--fake-audio (or FAKE_AUDIO=1) to use silent placeholder audio instead.`,
      );
    }
    await mkdir(options.audioStoreDir, { recursive: true });
    for (const name of missing) {
      const bytes = await provider.synthesize(wanted.get(name)!);
      await writeFile(path.join(options.audioStoreDir, name), bytes);
      stats.requested++;
    }
    log(`audio: generated ${stats.requested} file(s), reused ${stats.needed - stats.requested}`);
  }

  const missingSet = new Set(missing);
  const placeholderPlanned = new Set<string>();
  const locate = async (planned: { primary: Planned; fallback?: Planned }): Promise<LocatedAudio> => {
    if (!missingSet.has(planned.primary.name) || !placeholder || !planned.fallback) {
      return {
        ref: `audio/${planned.primary.name}`,
        file: path.join(options.audioStoreDir, planned.primary.name),
      };
    }
    const { name, request } = planned.fallback;
    const file = path.join(placeholder.storeDir, name);
    if (!placeholderPlanned.has(name)) {
      placeholderPlanned.add(name);
      if (!(await exists(file))) {
        await mkdir(placeholder.storeDir, { recursive: true });
        await writeFile(file, await placeholder.provider.synthesize(request));
      }
      stats.placeholders++;
    }
    return { ref: `audio/${name}`, file };
  };

  const lists: ResolvedAudio['lists'] = [];
  for (const items of plans) {
    const resolved: Array<Record<Rendition, LocatedAudio>> = [];
    for (const item of items) resolved.push({ normal: await locate(item.normal), slow: await locate(item.slow) });
    lists.push(resolved);
  }
  if (usePlaceholder) log(`audio: ${missing.length} file(s) missing, using silent placeholder audio (not committed)`);

  if (options.prune) stats.pruned = await pruneStore(options.audioStoreDir, new Set(wanted.keys()));
  if (stats.pruned.length > 0) log(`audio: pruned ${stats.pruned.length} unreferenced file(s)`);

  return { lists, stats };
}

/** Remove audio files in the store that are not in `keep`. Anything that is not an audio file is left alone. */
async function pruneStore(storeDir: string, keep: Set<string>): Promise<string[]> {
  let entries: string[];
  try {
    entries = await readdir(storeDir);
  } catch {
    return [];
  }
  const removed = entries.filter((name) => AUDIO_FILE.test(name) && !keep.has(name)).sort();
  for (const name of removed) await rm(path.join(storeDir, name), { force: true });
  return removed;
}

function plan(
  provider: TtsProvider,
  tts: TtsConfig,
  item: SourceList['items'][number],
  rendition: Rendition,
  label: string,
): Planned {
  const rate = tts.rates[rendition];
  const ssml = buildSsml(item, tts, rate, { pinyin: itemPinyin(item), phonemes: provider.supportsPhonemes });
  const digest = createHash('sha256')
    .update(JSON.stringify([provider.id, tts.voice, rate, tts.format, ssml]))
    .digest('hex')
    .slice(0, 32);
  return {
    name: `${digest}.${provider.extension}`,
    request: { text: spokenPrompt(item), ssml, voice: tts.voice, rate, format: tts.format, label },
  };
}

async function exists(file: string): Promise<boolean> {
  try {
    await stat(file);
    return true;
  } catch {
    return false;
  }
}
